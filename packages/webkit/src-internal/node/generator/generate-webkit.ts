import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { isAbsolute, join, resolve } from 'node:path';
import { parseEnv } from 'node:util';

import {
  type WebKitConfigDefinition,
  type WebKitEnvironmentFields,
  type WebKitEnvironmentValues,
  isWebKitEnvironmentVariable,
  resolveWebKitPublicConfig,
} from '@neutral/configuration';

export interface GenerateWebKitOptions {
  /** Application root containing environment.config.ts and package.json. */
  readonly dir: string;
  /** The parsed environment definition, loaded by the CLI at build time. */
  readonly definition: WebKitConfigDefinition;
  /** Explicit build inputs. Process ENV takes precedence over optional dotenv values. */
  readonly env?: WebKitEnvironmentValues;
  readonly envFile?: string;
}

export interface GenerateWebKitResult {
  readonly outputDir: string;
  readonly files: readonly string[];
}

/** Generate isolated, typed public and private outputs without embedding private ENV. */
export function generateWebKit(options: GenerateWebKitOptions): GenerateWebKitResult {
  const root = resolve(options.dir);
  const envFile = options.envFile
    ? isAbsolute(options.envFile)
      ? options.envFile
      : join(root, options.envFile)
    : undefined;
  const fromFile = envFile ? parseEnv(readFileSync(envFile, 'utf8')) : {};
  const environment = { ...fromFile, ...(options.env ?? process.env) };
  const publicValues = resolveWebKitPublicConfig(options.definition, environment);
  const publicSnapshot = replaceMissingWithEmptyString(publicValues);
  const privatePlaceholders = makePlaceholders(options.definition.private);

  const outputDir = join(root, '.webkit');
  mkdirSync(outputDir, { recursive: true });

  const artifacts = new Map<string, string>([
    [
      'public.mjs',
      `// Generated by webkit build. Public build-time values; do not edit.\nexport default ${JSON.stringify(publicSnapshot, null, 2)};\n`,
    ],
    ['public.d.mts', emitDeclaration('environment', options.definition.public)],
    [
      'private.mjs',
      `// Generated by webkit build. Placeholders only; never contains secrets.\nexport default ${JSON.stringify(privatePlaceholders, null, 2)};\n`,
    ],
    ['private.d.mts', emitDeclaration('environment', options.definition.private)],
  ]);

  // Remove the generated preload left by WebKit versions that supported runtime overrides.
  rmSync(join(outputDir, 'runtime.mjs'), { force: true });

  for (const [name, contents] of artifacts) {
    writeFileSync(join(outputDir, name), contents, 'utf8');
  }

  return { outputDir: outputDir, files: [...artifacts.keys()] };
}

function replaceMissingWithEmptyString(value: unknown): unknown {
  if (value === undefined) return '';
  if (typeof value === 'string') return value;
  if (value !== null && typeof value === 'object' && !Array.isArray(value)) {
    return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, replaceMissingWithEmptyString(item)]));
  }
  throw new Error('WebKit public environment must contain ENV string fields only.');
}

function makePlaceholders(fields: WebKitEnvironmentFields, path: readonly string[] = []): Record<string, unknown> {
  return Object.fromEntries(
    Object.entries(fields).map(([key, field]) => {
      if (isWebKitEnvironmentVariable(field)) {
        if (field.fallback !== undefined) {
          throw new Error(
            `Private ENV defaults cannot be embedded in generated artifacts: ${[...path, key].join('.')}`,
          );
        }
        return [key, ''];
      }

      return [key, makePlaceholders(field, [...path, key])];
    }),
  );
}

function emitDeclaration(name: string, fields: WebKitEnvironmentFields): string {
  return `// Generated by webkit build.\ndeclare const ${name}: ${emitType(fields, 0)};\nexport default ${name};\n`;
}

function emitType(fields: WebKitEnvironmentFields, depth: number): string {
  const indent = '  '.repeat(depth);
  const body = Object.entries(fields).map(([key, field]) => {
    const type = isWebKitEnvironmentVariable(field) ? 'string' : emitType(field, depth + 1);
    return `${indent}  readonly ${JSON.stringify(key)}: ${type};`;
  });
  return body.length ? `{\n${body.join('\n')}\n${indent}}` : '{}';
}
